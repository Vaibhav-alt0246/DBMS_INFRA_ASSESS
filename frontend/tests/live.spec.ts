import { test, expect } from '@playwright/test';

test('live PostgreSQL: create asset and incident, link, complete maintenance, inspect reports and search', async ({page,request}) => {
 test.skip(process.env.LIVE_BROWSER !== '1', 'Requires disposable live API on port 8000');
 test.setTimeout(120000);
 const headers={Authorization:'Bearer test-admin'};
 const api='http://127.0.0.1:8000';
 const locations=await (await request.get(api+'/api/locations',{headers})).json();
 const categories=await (await request.get(api+'/api/categories',{headers})).json();
 const technicians=await (await request.get(api+'/api/technicians',{headers})).json();
 const code='BROWSER-'+Date.now();
 await page.goto('/');
 await page.getByLabel('Access token').fill('test-admin');
 await page.getByRole('button',{name:'Connect',exact:true}).click();
 await page.getByRole('button',{name:'Components',exact:true}).click();
 await page.getByRole('button',{name:'＋ Add',exact:true}).click();
 await page.getByRole('textbox',{name:'Asset tag',exact:true}).fill(code);
 await page.getByRole('combobox',{name:/^Location ID/}).selectOption(String(locations[0].location_id));
 await page.getByRole('combobox',{name:/^Category ID/}).selectOption(String(categories[0].category_id));
 await page.getByLabel('Name',{exact:true}).fill(code+' pump');
 await page.getByRole('combobox',{name:/^Status/}).selectOption('OPERATIONAL');
 await page.getByRole('button',{name:'Save record',exact:true}).click();
 await expect(page.getByRole('button',{name:code+' pump OPERATIONAL',exact:true})).toBeVisible();
 const assets=await (await request.get(api+'/api/components?search='+code,{headers})).json();
 const component=assets[0].component_id;
 await page.getByRole('button',{name:'Incidents',exact:true}).click();
 await page.getByRole('button',{name:'＋ Add',exact:true}).click();
 await page.getByLabel('Incident number',{exact:true}).fill(code);
 await page.getByLabel('Reported at',{exact:true}).fill('2026-11-14T10:00');
 await page.getByRole('combobox',{name:/^Severity/}).last().selectOption('HIGH');
 await page.getByRole('combobox',{name:/^Status/}).selectOption('OPEN');
 await page.getByLabel('Title',{exact:true}).fill(code+' seal leak');
 await page.getByLabel('Description',{exact:true}).fill('Pump leaking at the seal');
 await page.getByRole('button',{name:'Save record',exact:true}).click();
 await page.getByRole('button',{name:code+' seal leak OPEN',exact:true}).click();
 await page.locator('.detail select').selectOption(String(component));
 await page.getByRole('button',{name:'Link component',exact:true}).click();
 await expect(page.locator('.detail')).toContainText('['+code+']');
 const incidents=await (await request.get(api+'/api/incidents?search='+code,{headers})).json();
 const order=await request.post(api+'/api/work-orders',{headers,data:{work_order_number:code,component_id:component,incident_id:incidents[0].incident_id,technician_id:technicians[0].technician_id,work_type:'CORRECTIVE',planned_start:'2026-01-01'}});
 expect(order.status()).toBe(201);
 await page.getByRole('button',{name:'Work orders',exact:true}).click();
 await page.getByRole('button',{name:code+' PLANNED',exact:true}).click();
 await page.getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByRole('button',{name:'Complete Work Order',exact:true}).click();
 await page.getByRole('combobox',{name:/^Technician ID/}).selectOption(String(technicians[0].technician_id));
 await page.getByLabel('Action taken / maintenance notes').fill('Replaced pump seal');
 await page.getByLabel('Actual repair cost').fill('123.45');
 await page.getByLabel('Outcome').selectOption('SUCCESSFUL');
 await page.getByLabel('Completed at').fill('2026-11-14T12:00');
 await page.getByLabel('Resolution notes').fill('Pressure tested and verified');
 await page.getByRole('button',{name:'Complete Work Order',exact:true}).click();
 await expect(page.getByRole('button',{name:code+' COMPLETED',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Maintenance alerts',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Maintenance alerts',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'health report',exact:true}).click();
 await expect(page.getByRole('heading',{name:'health report',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.getByPlaceholder('pump vibrating and leaking').fill('pump seal leak');
 await page.getByRole('button',{name:'Search ↗'}).click();
 await expect(page.getByRole('heading',{name:'Search results'})).toBeVisible({timeout:60000});
 await expect(page.locator('.table .row').first()).toBeVisible();
});
