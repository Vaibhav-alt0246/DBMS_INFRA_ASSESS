CREATE OR REPLACE FUNCTION fn_audit_entity() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE before_row jsonb; after_row jsonb;
BEGIN
 IF TG_OP <> 'INSERT' THEN before_row := to_jsonb(OLD); END IF;
 IF TG_OP <> 'DELETE' THEN after_row := to_jsonb(NEW); END IF;
 IF before_row IS DISTINCT FROM after_row THEN
  INSERT INTO audit_log(entity_type,entity_id,action,old_values,new_values,changed_by)
  VALUES(TG_TABLE_NAME,(coalesce(after_row,before_row)->>TG_ARGV[0])::bigint,TG_OP,before_row,after_row,
   coalesce(nullif(current_setting('app.user',true),''),session_user));
 END IF;
 RETURN coalesce(NEW,OLD);
END $$;
