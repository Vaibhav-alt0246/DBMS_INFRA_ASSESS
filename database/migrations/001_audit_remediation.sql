CREATE TABLE IF NOT EXISTS sensor_threshold (
 threshold_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 component_id bigint NOT NULL REFERENCES component ON DELETE RESTRICT,
 sensor_type varchar(40) NOT NULL, unit varchar(20) NOT NULL,
 min_value numeric(14,4), max_value numeric(14,4),
 CHECK(min_value IS NOT NULL OR max_value IS NOT NULL),
 CHECK(min_value IS NULL OR max_value IS NULL OR min_value<=max_value),
 UNIQUE(component_id,sensor_type,unit)
);
