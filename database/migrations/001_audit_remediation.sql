CREATE OR REPLACE FUNCTION fn_workflow_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE order_status text;
BEGIN
 IF TG_TABLE_NAME='work_order' AND TG_OP='UPDATE' THEN
  IF OLD.status IN ('COMPLETED','CANCELLED') AND NEW IS DISTINCT FROM OLD THEN
   RAISE EXCEPTION 'Terminal work orders are immutable' USING ERRCODE='55000';
  END IF;
 END IF;
 IF TG_OP='INSERT' OR NEW.technician_id IS DISTINCT FROM OLD.technician_id THEN
  IF NEW.technician_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM technician WHERE technician_id=NEW.technician_id AND active FOR SHARE) THEN
   RAISE EXCEPTION 'An active technician is required' USING ERRCODE='23514';
  END IF;
 END IF;
 IF TG_TABLE_NAME='maintenance_record' THEN
  SELECT status INTO order_status FROM work_order WHERE work_order_id=NEW.work_order_id FOR UPDATE;
  IF order_status IN ('CANCELLED','COMPLETED') THEN
   RAISE EXCEPTION 'Cannot change maintenance for terminal orders' USING ERRCODE='55000';
  END IF;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_workflow_guard ON work_order;
CREATE TRIGGER trg_workflow_guard BEFORE INSERT OR UPDATE ON work_order FOR EACH ROW EXECUTE FUNCTION fn_workflow_guard();
DROP TRIGGER IF EXISTS trg_workflow_guard ON maintenance_record;
CREATE TRIGGER trg_workflow_guard BEFORE INSERT OR UPDATE ON maintenance_record FOR EACH ROW EXECUTE FUNCTION fn_workflow_guard();

