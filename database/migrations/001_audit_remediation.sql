CREATE OR REPLACE FUNCTION fn_refresh_alerts() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
 -- One reconciliation transaction across all sources prevents duplicate/contradictory alerts.
 PERFORM pg_advisory_xact_lock(6408321);
 CREATE TEMP TABLE IF NOT EXISTS desired_alerts(component_id bigint, assessment_id bigint, alert_type text, message text) ON COMMIT DROP;
 TRUNCATE desired_alerts;
 INSERT INTO desired_alerts
 SELECT component_id,assessment_id,'CRITICAL_HEALTH','Latest health score is at or below 70; review corrective work.'
 FROM (SELECT DISTINCT ON(component_id) * FROM assessment WHERE assessed_at<=clock_timestamp() ORDER BY component_id,assessed_at DESC,assessment_id DESC) a WHERE health_score<=70;
 INSERT INTO desired_alerts
 SELECT DISTINCT c.component_id,NULL::bigint,'OVERDUE_MAINTENANCE','An active work order is past its planned end/start date.'
 FROM work_order w JOIN component c ON c.component_id=w.component_id OR EXISTS(SELECT 1 FROM incident_component ic WHERE ic.incident_id=w.incident_id AND ic.component_id=c.component_id)
 WHERE w.status NOT IN ('COMPLETED','CANCELLED') AND coalesce(w.planned_end,w.planned_start)<current_date;
 INSERT INTO desired_alerts
 SELECT DISTINCT s.component_id,NULL::bigint,'SENSOR_ANOMALY','Latest sensor reading exceeds configured asset thresholds.'
 FROM sensor_threshold t JOIN LATERAL (SELECT * FROM sensor_reading s WHERE s.component_id=t.component_id AND s.sensor_type=t.sensor_type AND s.unit=t.unit AND s.recorded_at<=clock_timestamp() ORDER BY recorded_at DESC,reading_id DESC LIMIT 1) s ON true
 WHERE s.reading_value<t.min_value OR s.reading_value>t.max_value;
 UPDATE maintenance_alert a SET status='RESOLVED',verified_at=now(),verification_notes='Automatically verified: source condition recovered.'
 WHERE status IN ('OPEN','ACKNOWLEDGED') AND NOT EXISTS(SELECT 1 FROM desired_alerts d WHERE d.component_id=a.component_id AND d.alert_type=a.alert_type);
 UPDATE maintenance_alert a SET assessment_id=d.assessment_id,message=d.message
 FROM desired_alerts d WHERE a.component_id=d.component_id AND a.alert_type=d.alert_type AND a.status IN ('OPEN','ACKNOWLEDGED') AND (a.assessment_id IS DISTINCT FROM d.assessment_id OR a.message IS DISTINCT FROM d.message);
 INSERT INTO maintenance_alert(component_id,assessment_id,alert_type,status,message)
 SELECT d.component_id,d.assessment_id,d.alert_type,'OPEN',d.message FROM desired_alerts d
 WHERE NOT EXISTS(SELECT 1 FROM maintenance_alert a WHERE a.component_id=d.component_id AND a.alert_type=d.alert_type AND a.status IN ('OPEN','ACKNOWLEDGED'))
 ON CONFLICT DO NOTHING;
END $$;
