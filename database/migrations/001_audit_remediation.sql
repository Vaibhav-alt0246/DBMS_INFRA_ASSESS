-- Preserve completion evidence and validate remediation ownership/verification.
CREATE OR REPLACE FUNCTION fn_maintenance_history_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE current_status text;
BEGIN
 SELECT status INTO current_status FROM work_order WHERE work_order_id=OLD.work_order_id FOR UPDATE;
 IF current_status IN ('COMPLETED','CANCELLED') THEN
  RAISE EXCEPTION 'Terminal maintenance history is immutable' USING ERRCODE='55000';
 END IF;
 RETURN coalesce(NEW,OLD);
END $$;
DROP TRIGGER IF EXISTS trg_maintenance_history_guard ON maintenance_record;
CREATE TRIGGER trg_maintenance_history_guard BEFORE UPDATE OR DELETE ON maintenance_record FOR EACH ROW EXECUTE FUNCTION fn_maintenance_history_guard();
CREATE OR REPLACE FUNCTION fn_alert_remediation_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.owner_id IS DISTINCT FROM OLD.owner_id AND NEW.owner_id IS NOT NULL THEN
  IF NOT EXISTS(SELECT 1 FROM technician WHERE technician_id=NEW.owner_id AND active FOR SHARE) THEN
   RAISE EXCEPTION 'Alert owner must be active' USING ERRCODE='23514';
  END IF;
 END IF;
 IF NEW.remediation_work_order_id IS NOT NULL AND NEW.remediation_work_order_id IS DISTINCT FROM OLD.remediation_work_order_id THEN
  IF NOT EXISTS(SELECT 1 FROM work_order w WHERE w.work_order_id=NEW.remediation_work_order_id AND (w.component_id=NEW.component_id OR EXISTS(SELECT 1 FROM incident_component ic WHERE ic.incident_id=w.incident_id AND ic.component_id=NEW.component_id))) THEN
   RAISE EXCEPTION 'Remediation work order must relate to this asset' USING ERRCODE='23514';
  END IF;
 END IF;
 IF NEW.status='RESOLVED' AND OLD.status IS DISTINCT FROM 'RESOLVED' THEN
  IF nullif(btrim(NEW.verification_notes),'') IS NULL THEN
   RAISE EXCEPTION 'Resolution requires verification notes' USING ERRCODE='23514';
  END IF;
  NEW.verified_at:=clock_timestamp();
 ELSIF NEW.status<>'RESOLVED' THEN
  NEW.verified_at:=NULL;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_alert_remediation_guard ON maintenance_alert;
CREATE TRIGGER trg_alert_remediation_guard BEFORE UPDATE ON maintenance_alert FOR EACH ROW EXECUTE FUNCTION fn_alert_remediation_guard();
