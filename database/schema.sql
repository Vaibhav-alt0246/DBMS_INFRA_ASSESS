-- InfraAssess Phase 1. Run against PostgreSQL 14+.
CREATE TABLE location (
    location_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_code varchar(30) NOT NULL UNIQUE,
    name varchar(120) NOT NULL,
    address varchar(250) NOT NULL,
    region varchar(80) NOT NULL
);

CREATE TABLE component_category (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code varchar(30) NOT NULL UNIQUE,
    name varchar(100) NOT NULL UNIQUE,
    description text
);

CREATE TABLE component (
    component_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_tag varchar(40) NOT NULL UNIQUE,
    location_id bigint NOT NULL REFERENCES location(location_id) ON DELETE RESTRICT,
    category_id bigint NOT NULL REFERENCES component_category(category_id) ON DELETE RESTRICT,
    name varchar(150) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'OPERATIONAL' CHECK (status IN ('OPERATIONAL','DEGRADED','OUT_OF_SERVICE','RETIRED')),
    installed_on date,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE technician (
    technician_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code varchar(30) NOT NULL UNIQUE,
    full_name varchar(120) NOT NULL,
    email varchar(160) NOT NULL UNIQUE,
    specialty varchar(100) NOT NULL,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE assessment (
    assessment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id bigint NOT NULL REFERENCES component(component_id) ON DELETE RESTRICT,
    technician_id bigint NOT NULL REFERENCES technician(technician_id) ON DELETE RESTRICT,
    assessed_at timestamptz NOT NULL,
    health_score numeric(5,2) NOT NULL CHECK (health_score BETWEEN 0 AND 100),
    condition_status varchar(20) NOT NULL CHECK (condition_status IN ('GOOD','FAIR','POOR','CRITICAL')),
    findings text NOT NULL
);

CREATE TABLE incident (
    incident_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_number varchar(30) NOT NULL UNIQUE,
    reported_at timestamptz NOT NULL,
    severity varchar(10) NOT NULL CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    status varchar(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','INVESTIGATING','RESOLVED','CLOSED')),
    title varchar(180) NOT NULL,
    description text NOT NULL,
    resolved_at timestamptz,
    CHECK (resolved_at IS NULL OR resolved_at >= reported_at)
);

CREATE TABLE incident_component (
    incident_id bigint NOT NULL REFERENCES incident(incident_id) ON DELETE RESTRICT,
    component_id bigint NOT NULL REFERENCES component(component_id) ON DELETE RESTRICT,
    impact_type varchar(20) NOT NULL CHECK (impact_type IN ('PRIMARY','SECONDARY','POTENTIAL')),
    notes text,
    PRIMARY KEY (incident_id, component_id)
);

CREATE TABLE work_order (
    work_order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_number varchar(30) NOT NULL UNIQUE,
    incident_id bigint REFERENCES incident(incident_id) ON DELETE RESTRICT,
    component_id bigint REFERENCES component(component_id) ON DELETE RESTRICT,
    technician_id bigint REFERENCES technician(technician_id) ON DELETE RESTRICT,
    work_type varchar(12) NOT NULL CHECK (work_type IN ('CORRECTIVE','PREVENTIVE')),
    status varchar(15) NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED','ASSIGNED','IN_PROGRESS','COMPLETED','CANCELLED')),
    planned_start date NOT NULL,
    planned_end date,
    completed_at timestamptz,
    estimated_cost numeric(12,2) NOT NULL DEFAULT 0 CHECK (estimated_cost >= 0),
    completion_notes text,
    CHECK (component_id IS NOT NULL OR incident_id IS NOT NULL),
    CHECK (planned_end IS NULL OR planned_end >= planned_start),
    CHECK (completed_at IS NULL OR completed_at >= planned_start::timestamptz),
    CHECK (status <> 'COMPLETED' OR completion_notes IS NOT NULL)
);

CREATE TABLE maintenance_record (
    maintenance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id bigint NOT NULL REFERENCES work_order(work_order_id) ON DELETE RESTRICT,
    technician_id bigint NOT NULL REFERENCES technician(technician_id) ON DELETE RESTRICT,
    performed_at timestamptz NOT NULL,
    action_taken text NOT NULL,
    actual_cost numeric(12,2) NOT NULL CHECK (actual_cost >= 0),
    outcome varchar(20) NOT NULL CHECK (outcome IN ('SUCCESSFUL','PARTIAL','UNSUCCESSFUL'))
);

CREATE TABLE sensor_reading (
    reading_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id bigint NOT NULL REFERENCES component(component_id) ON DELETE RESTRICT,
    recorded_at timestamptz NOT NULL,
    sensor_type varchar(40) NOT NULL,
    reading_value numeric(14,4) NOT NULL CHECK (reading_value >= 0),
    unit varchar(20) NOT NULL
);

CREATE TABLE maintenance_alert (
    alert_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id bigint NOT NULL REFERENCES component(component_id) ON DELETE RESTRICT,
    assessment_id bigint REFERENCES assessment(assessment_id) ON DELETE RESTRICT,
    alert_type varchar(30) NOT NULL CHECK (alert_type IN ('CRITICAL_HEALTH','OVERDUE_MAINTENANCE','SENSOR_ANOMALY')),
    status varchar(15) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ACKNOWLEDGED','RESOLVED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    message text NOT NULL,
    UNIQUE (component_id, assessment_id, alert_type)
);

CREATE TABLE audit_log (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type varchar(40) NOT NULL,
    entity_id bigint NOT NULL,
    action varchar(20) NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
    old_values jsonb,
    new_values jsonb,
    changed_at timestamptz NOT NULL DEFAULT now(),
    changed_by varchar(120)
);

CREATE INDEX idx_component_location ON component(location_id);
CREATE INDEX idx_component_category ON component(category_id);
CREATE INDEX idx_assessment_component_time ON assessment(component_id, assessed_at DESC);
CREATE INDEX idx_incident_status_severity ON incident(status, severity);
CREATE INDEX idx_incident_component_component ON incident_component(component_id);
CREATE INDEX idx_work_order_status_dates ON work_order(status, planned_start);
CREATE INDEX idx_work_order_component ON work_order(component_id);
CREATE INDEX idx_maintenance_work_order ON maintenance_record(work_order_id);
CREATE INDEX idx_sensor_component_time ON sensor_reading(component_id, recorded_at DESC);
CREATE INDEX idx_alert_status ON maintenance_alert(status, created_at);
CREATE INDEX idx_audit_entity_time ON audit_log(entity_type, entity_id, changed_at DESC);
